#!/usr/bin/env python3
"""The M3 benchmark: scores that a pull request must not lower.

    make test && make benchmark          # check the latest M3 report against the baseline
    make test && make benchmark-baseline # lock in a higher score (then commit the file)

``--check`` (the default) reads the newest ``.m3/reports/*/feedback.json`` and the tool registry,
and compares them with ``benchmarks/baseline.json``. What is measured, all offline:

1. Passing tests. Every test id that passes in the baseline must still exist and pass. New tests
   are fine.
2. M3 server-call coverage. Per test group (each adapter, plus the fixture-agent and core groups)
   the number of tests that produced an M3 execution id must not drop, and neither may the total
   number of completed M3 executions.
3. M3 evaluator pass rates (``evaluation_stats.<evaluator>.pass_rate`` in feedback.json).
4. The tool catalog. The set of registered tools must not shrink.

Why this does not just call ``m3 test --baseline RUN_ID``: M3's comparison reads an earlier run
from the local SQLite results database (``.m3/executions.sqlite``, ignored by git, about 200 MB
here) and refuses to run without it ("baseline run was not found"). A fresh CI checkout has no
such database, a run id is not something you can commit, and the comparison does not cover the
tool catalog or per-adapter coverage. So the baseline is a small committed JSON file instead.

CI on a pull request (see .github/workflows/ci.yml) compares against the baseline from the base
side of the pull request's merge commit, not the copy in the pull request, so lowering the file
cannot get a run through by accident::

    benchmark.py --baseline base-baseline.json --pr-baseline benchmarks/baseline.json

CI also runs the base side's copy of this script, so a change to this file takes effect after it
merges; until the base has the file, CI falls back to the pull request's copy and says so. Be
clear about what this is: a guard against accidental or casual edits. It is not a security
boundary. A pull request runs its own workflow file, and its own test code runs in the job that
writes the M3 report, so a hostile change can get around any check here. Maintainer review
(.github/CODEOWNERS, branch protection) is the real control.

That runs three comparisons: the run against main's baseline, the pull request's baseline file
against main's (it may be raised, never lowered), and the run against the pull request's own
baseline (so main's push check cannot fail after a merge). A maintainer can wave the first two
through by putting the ``benchmark-change-approved`` label on the pull request (read from the
``BENCHMARK_PR_LABELS`` environment variable, a JSON list of label names). The third cannot be
waved through: an approved drop must come with a lower ``benchmarks/baseline.json`` in the same
pull request.

``--update`` rewrites the baseline from the latest report. It refuses to write from a run that has
failing tests, and refuses to lower the baseline unless ``--allow-lower`` is given, so a partial
run cannot shrink it by accident.

``--agent CURRENT.json --baseline COMMITTED.json`` is the nightly check. Each prompt's agent
tool-selection pass rate (``docs/results/agent-<harness>-latest.json``) must not drop below the
committed file by more than one trial: agents are not deterministic, so a prompt regresses only
when ``new_passed/new_total < base_rate - 1/new_total``. With 3 trials, one extra miss passes and
two fail.

Exit codes: 0 ok, 1 a score went down, 2 the input could not be read.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from dataclasses import dataclass, field
from fractions import Fraction
from pathlib import Path

# CI runs main's copy of this file from a temporary directory (see the module docstring), so the
# repository root cannot always be found from __file__: BENCHMARK_ROOT names it in that case.
ROOT = Path(os.environ.get("BENCHMARK_ROOT") or Path(__file__).resolve().parents[1])
sys.path.insert(0, str(ROOT / "src"))

SCHEMA_VERSION = 1
BASELINE_PATH = ROOT / "benchmarks" / "baseline.json"
REPORTS_DIR = ROOT / ".m3" / "reports"
APPROVAL_LABEL = "benchmark-change-approved"
LABELS_ENV = "BENCHMARK_PR_LABELS"
ABOUT = (
    "Scores a pull request must not lower. Generated by `make benchmark-baseline` from an M3 "
    "report; do not edit by hand. See the 'CI and the M3 benchmark' section of CONTRIBUTING.md."
)
UP, SAME, DOWN = "↑ improved", "= same", "↓ regressed"
DIPPED = "~ dipped, within 1 trial"  # agent lane only: lower, but inside the tolerance
MANY_MISSING = 10  # this many tests missing from a run suggests a partial run
MAX_DETAIL = 8  # ids listed per metric before "and N more"


@dataclass
class Row:
    metric: str
    baseline: str
    now: str
    status: str
    detail: list[str] = field(default_factory=list)


# --------------------------------------------------------------------------------------------
# Reading a report
# --------------------------------------------------------------------------------------------


def latest_report(reports_dir: Path) -> Path | None:
    """The newest ``feedback.json`` under ``reports_dir``, or None when there is none."""
    candidates = sorted(reports_dir.glob("*/feedback.json"), key=lambda p: p.stat().st_mtime)
    return candidates[-1] if candidates else None


def group_of(node_id: str) -> str:
    """The coverage group of a test: ``adapters/<name>`` or the top directory under m3_tests."""
    parts = node_id.split("::")[0].split("/")
    if len(parts) >= 3 and parts[0] == "m3_tests" and parts[1] == "adapters":
        return f"adapters/{parts[2]}"
    if len(parts) >= 3 and parts[0] == "m3_tests":
        return parts[1]
    return parts[0]


def report_problems(feedback: dict) -> list[str]:
    """Reasons the report cannot be trusted as a measurement (not the same as failing tests)."""
    summary = feedback.get("summary", {})
    problems = []
    if summary.get("run_status") != "finished":
        problems.append(f"the M3 run did not finish (run_status={summary.get('run_status')!r})")
    if not feedback.get("tests"):
        problems.append("the report contains no tests")
    if summary.get("collection_errors"):
        problems.append(f"{summary['collection_errors']} collection error(s)")
    return problems


def extract_metrics(feedback: dict, tool_names: list[str]) -> dict:
    """Reduce a feedback.json and the tool registry to the benchmark metrics.

    The result is the baseline schema plus ``other_tests`` (test id to outcome for tests that did
    not pass), which ``compare`` uses to word its messages and ``dump_baseline`` leaves out.
    """
    tests = feedback.get("tests", [])
    passing = sorted(t["node_id"] for t in tests if t["outcome"] == "passed")
    other = {t["node_id"]: t["outcome"] for t in tests if t["outcome"] != "passed"}
    with_execution: dict[str, int] = {}
    for test in tests:
        if test.get("execution_ids"):
            group = group_of(test["node_id"])
            with_execution[group] = with_execution.get(group, 0) + 1
    summary = feedback.get("summary", {})
    executions = summary.get("terminal_executions", summary.get("executions", 0))
    rates = {
        name: round(float(stats["pass_rate"]), 6)
        for name, stats in feedback.get("evaluation_stats", {}).items()
        if stats.get("pass_rate") is not None
    }
    return {
        "schema_version": SCHEMA_VERSION,
        "passing_tests": passing,
        "m3_calls": {
            "executions_total": int(executions),
            "tests_with_execution": dict(sorted(with_execution.items())),
        },
        "evaluator_pass_rates": dict(sorted(rates.items())),
        "tools": sorted(tool_names),
        "other_tests": other,
    }


def dump_baseline(metrics: dict) -> str:
    """The committed form: sorted keys, two-space indent, no timestamps, trailing newline."""
    document = {k: v for k, v in metrics.items() if k != "other_tests"}
    document["about"] = ABOUT
    return json.dumps(document, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def load_baseline(path: Path) -> dict:
    """Read and validate a baseline file; raises ValueError with a readable message."""
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise ValueError(f"cannot read baseline {path}: {exc}") from exc
    try:
        if data["schema_version"] != SCHEMA_VERSION:
            raise ValueError(f"{path} has schema_version {data['schema_version']!r}")
        ok = (
            isinstance(data["passing_tests"], list)
            and isinstance(data["tools"], list)
            and isinstance(data["evaluator_pass_rates"], dict)
            and isinstance(data["m3_calls"]["executions_total"], int)
            and isinstance(data["m3_calls"]["tests_with_execution"], dict)
        )
    except (KeyError, TypeError) as exc:
        raise ValueError(f"{path} does not match the baseline schema (problem at {exc!r})") from exc
    if not ok:
        raise ValueError(f"{path} does not match the baseline schema")
    return data


# --------------------------------------------------------------------------------------------
# Comparing
# --------------------------------------------------------------------------------------------


def _status(baseline: float, now: float) -> str:
    if now < baseline - 1e-9:
        return DOWN
    return UP if now > baseline + 1e-9 else SAME


def _more(items: list[str]) -> list[str]:
    if len(items) <= MAX_DETAIL:
        return items
    return [*items[:MAX_DETAIL], f"... and {len(items) - MAX_DETAIL} more"]


def _pct(rate: float | None) -> str:
    return "missing" if rate is None else f"{rate * 100:.1f}%"


def compare(baseline: dict, current: dict) -> list[Row]:
    """Compare two metric dicts. Pure: a row is DOWN when a score is lower than the baseline."""
    rows: list[Row] = []

    # 1. Passing tests: every baseline id must still pass. New tests only raise the count.
    base_tests, now_tests = set(baseline["passing_tests"]), set(current["passing_tests"])
    other = current.get("other_tests", {})
    lost = sorted(base_tests - now_tests)
    detail = [
        f"{node}: {'now ' + other[node] if node in other else 'missing from this run'}"
        for node in lost
    ]
    status = DOWN if lost else _status(len(base_tests), len(now_tests))
    rows.append(Row("Passing tests", str(len(base_tests)), str(len(now_tests)), status, detail))

    # 2. M3 server-call coverage, per group and in total.
    base_calls, now_calls = baseline["m3_calls"], current["m3_calls"]
    base_groups, now_groups = base_calls["tests_with_execution"], now_calls["tests_with_execution"]
    for group in sorted(set(base_groups) | set(now_groups)):
        before, after = base_groups.get(group, 0), now_groups.get(group, 0)
        rows.append(
            Row(f"M3-recorded tests: {group}", str(before), str(after), _status(before, after))
        )
    rows.append(
        Row(
            "M3 executions (total)",
            str(base_calls["executions_total"]),
            str(now_calls["executions_total"]),
            _status(base_calls["executions_total"], now_calls["executions_total"]),
        )
    )

    # 3. Evaluator pass rates. An evaluator that disappeared counts as a drop.
    base_rates, now_rates = baseline["evaluator_pass_rates"], current["evaluator_pass_rates"]
    for name in sorted(set(base_rates) | set(now_rates)):
        before, after = base_rates.get(name), now_rates.get(name)
        if before is None:
            status = UP
        elif after is None:
            status = DOWN
        else:
            status = _status(before, after)
        rows.append(Row(f"Evaluator pass rate: {name}", _pct(before), _pct(after), status))

    # 4. Tool catalog: the set must not shrink.
    base_tools, now_tools = set(baseline["tools"]), set(current["tools"])
    removed = sorted(base_tools - now_tools)
    status = DOWN if removed else _status(len(base_tools), len(now_tools))
    rows.append(
        Row(
            "Tools",
            str(len(base_tools)),
            str(len(now_tools)),
            status,
            [f"{t}: removed" for t in removed],
        )
    )
    return rows


def _case_rate(entry: dict) -> Fraction:
    return Fraction(entry["passed"], entry["total"]) if entry["total"] else Fraction(0)


def _show_case(entry: dict | None) -> str:
    return "missing" if entry is None else f"{entry['passed']}/{entry['total']}"


def agent_case_dropped(before: dict, after: dict) -> bool:
    """True when a prompt's pass rate fell by more than one trial's worth.

    ``new_passed/new_total < base_rate - 1/new_total``. Agents are not deterministic, so with 3
    trials one extra miss is tolerated and two are not. A prompt with no trials has dropped.
    """
    if not after["total"]:
        return True
    return _case_rate(after) < _case_rate(before) - Fraction(1, after["total"])


def compare_agent(baseline: dict, current: dict) -> list[Row]:
    """Compare two ``agent-<harness>-latest.json`` documents prompt by prompt."""
    rows = []
    base_cases, now_cases = baseline["results"], current["results"]
    for case in sorted(set(base_cases) | set(now_cases)):
        before, after = base_cases.get(case), now_cases.get(case)
        label = f"Agent prompt: {case}"
        if before is None:
            rows.append(Row(label, "missing", _show_case(after), UP))
        elif after is None:
            rows.append(
                Row(label, _show_case(before), "missing", DOWN, ["not measured in this run"])
            )
        else:
            old, new = _case_rate(before), _case_rate(after)
            if agent_case_dropped(before, after):
                status = DOWN
            elif new < old:
                status = DIPPED
            else:
                status = UP if new > old else SAME
            rows.append(Row(label, _show_case(before), _show_case(after), status))
    return rows


# --------------------------------------------------------------------------------------------
# Output
# --------------------------------------------------------------------------------------------


def render_table(rows: list[Row]) -> str:
    """A markdown table with padded columns, readable both raw and rendered."""
    header = ("Metric", "Baseline", "Now", "Status")
    body = [(r.metric, r.baseline, r.now, r.status) for r in rows]
    widths = [max(len(cell[i]) for cell in [header, *body]) for i in range(4)]

    def line(cells: tuple[str, ...]) -> str:
        return "| " + " | ".join(c.ljust(w) for c, w in zip(cells, widths, strict=True)) + " |"

    rule = "|" + "|".join("-" * (w + 2) for w in widths) + "|"
    return "\n".join([line(header), rule, *(line(cell) for cell in body)])


def regressions(rows: list[Row]) -> list[Row]:
    return [r for r in rows if r.status == DOWN]


def improvements(rows: list[Row]) -> list[Row]:
    return [r for r in rows if r.status == UP]


def describe(rows: list[Row]) -> str:
    """One bullet per regressed row: what dropped and by how much, with ids."""
    lines = []
    for row in rows:
        lines.append(f"  - {row.metric}: {row.baseline} -> {row.now}")
        lines.extend(f"      {item}" for item in _more(row.detail))
    return "\n".join(lines)


def approved(environ: dict[str, str]) -> bool:
    """True when the pull request carries the approval label (``BENCHMARK_PR_LABELS`` is JSON)."""
    raw = environ.get(LABELS_ENV, "")
    try:
        labels = json.loads(raw) if raw else []
    except json.JSONDecodeError:
        return False
    return isinstance(labels, list) and APPROVAL_LABEL in labels


def write_summary(markdown: str) -> None:
    path = os.environ.get("GITHUB_STEP_SUMMARY")
    if path:
        with Path(path).open("a", encoding="utf-8") as handle:
            handle.write(markdown + "\n")


FIX_HINT = (
    "How to fix it: find what the list above names (a deleted or failing test, a tool that no\n"
    "longer registers or that errors, a test that stopped calling the server) and restore it.\n"
    "Run `make test && make benchmark` to check. If the drop is intentional, for example you\n"
    "removed an API that no longer exists, say why in the pull request, run\n"
    "`make benchmark-baseline BENCH_ARGS=--allow-lower`, commit the new\n"
    f"benchmarks/baseline.json, and ask a maintainer to add the `{APPROVAL_LABEL}` label."
)
LOWERED_HINT = (
    "Do not lower benchmarks/baseline.json to make a run pass. Restore it from the base branch\n"
    "(`git checkout origin/main -- benchmarks/baseline.json`). If the drop is intentional, say\n"
    f"why in the pull request and ask a maintainer for the `{APPROVAL_LABEL}` label."
)
PARTIAL_RUN_HINT = (
    "Many baseline tests are missing from this run. Did you run the full `make test` first?\n"
    "`make benchmark` reads the latest M3 report, so a run of only some tests looks like a drop."
)
REGENERATE_HINT = (
    "Regenerate the file with `make test && make benchmark-baseline` (add\n"
    "`BENCH_ARGS=--allow-lower` if the drop is intentional) and commit benchmarks/baseline.json."
)
RAISE_HINT = (
    "Scores went up. Run `make benchmark-baseline` and commit benchmarks/baseline.json to lock\n"
    "in the higher score."
)


# --------------------------------------------------------------------------------------------
# Commands
# --------------------------------------------------------------------------------------------


def registry_tools() -> list[str]:
    from keyless_mcp.server import build_server

    return [name for adapter in build_server().adapters for name in adapter.tool_names]


def current_metrics(report: Path | None, reports_dir: Path) -> tuple[Path, dict]:
    path = report or latest_report(reports_dir)
    if path is None or not path.is_file():
        raise ValueError(f"no feedback.json under {reports_dir}. Run `make test` first.")
    try:
        feedback = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise ValueError(f"cannot read {path}: {exc}") from exc
    if problems := report_problems(feedback):
        raise ValueError(f"{path} is not a usable measurement: " + "; ".join(problems))
    return path, extract_metrics(feedback, registry_tools())


def _partial_run(rows: list[Row]) -> bool:
    """True when many baseline tests are missing from the run, as after running only some tests."""
    missing = sum(d.endswith("missing from this run") for row in rows for d in row.detail)
    return missing >= MANY_MISSING


@dataclass
class Verdict:
    rows: list[Row]
    messages: list[str]  # text blocks printed under the table, in order
    failed: bool


def judge(
    base: dict, current: dict, pr_base: dict | None = None, is_approved: bool = False
) -> Verdict:
    """Decide pass or fail. Pure, so the CI rules can be tested without a report on disk.

    Without ``pr_base`` (a local run, or a push to main) any drop against ``base`` fails. With it
    (a pull request), a drop against main's baseline, or a lower baseline file, fails unless
    ``is_approved``; a run that falls short of the pull request's own baseline file always fails.
    """
    is_approved = is_approved and pr_base is not None  # the label only means something on a PR
    rows = compare(base, current)
    messages: list[str] = []
    run_drops = regressions(rows)
    file_drops = regressions(compare(base, pr_base)) if pr_base is not None else []
    waivable = bool(run_drops or file_drops)
    failed = False
    if waivable and is_approved:
        messages.append(
            "Scores or the baseline file went down, and the pull request has the "
            f"`{APPROVAL_LABEL}` label, so a maintainer has allowed it."
        )
    else:
        if run_drops:
            failed = True
            hint = f"{PARTIAL_RUN_HINT}\n\n{FIX_HINT}" if _partial_run(run_drops) else FIX_HINT
            messages.append(
                "FAIL: benchmark scores went down against the base branch:\n"
                f"{describe(run_drops)}\n\n{hint}"
            )
        if file_drops:
            failed = True
            messages.append(
                "FAIL: benchmarks/baseline.json in this pull request is lower than the one on "
                f"the base branch:\n{describe(file_drops)}\n\n{LOWERED_HINT}"
            )
    if pr_base is not None:
        # A baseline that promises more than this run delivers would fail the push check on main
        # after the merge, so no label can wave it through.
        behind = regressions(compare(pr_base, current))
        if not is_approved:  # already reported above: do not list the same rows twice
            reported = {row.metric for row in run_drops}
            behind = [row for row in behind if row.metric not in reported]
        if behind:
            failed = True
            messages.append(
                "FAIL: the baseline file in this pull request promises more than this run "
                f"delivers:\n{describe(behind)}\n\n{REGENERATE_HINT}"
            )
    if not failed and improvements(rows):
        messages.append(RAISE_HINT)
    return Verdict(rows, messages, failed)


def run_check(args: argparse.Namespace) -> int:
    base = load_baseline(args.baseline)
    path, current = current_metrics(args.report, args.reports_dir)
    pr_base = load_baseline(args.pr_baseline) if args.pr_baseline else None
    verdict = judge(base, current, pr_base, approved(dict(os.environ)))
    label = f"{path.parent.name} vs {args.baseline.name}"
    table = render_table(verdict.rows)
    print(f"M3 benchmark: {label}\n\n{table}")
    for message in verdict.messages:
        print(f"\n{message}")
    if not verdict.failed:
        print("\nOK")
    blocks = [f"### M3 benchmark (scores must not go down)\n\n`{label}`\n\n{table}"]
    blocks += [f"```\n{message}\n```" for message in verdict.messages]
    write_summary("\n\n".join(blocks))
    return 1 if verdict.failed else 0


def run_update(args: argparse.Namespace) -> int:
    path, current = current_metrics(args.report, args.reports_dir)
    if current["other_tests"]:
        listed = ", ".join(f"{n} ({o})" for n, o in list(current["other_tests"].items())[:5])
        print(
            f"benchmark: not writing a baseline from a run with tests that did not pass: {listed}"
        )
        return 1
    if args.baseline.is_file() and not args.allow_lower:
        lowered = regressions(compare(load_baseline(args.baseline), current))
        if lowered:
            print("benchmark: this report would LOWER the baseline:")
            print(describe(lowered))
            print(
                "\nIf that is not intended, you probably ran only part of the suite: run "
                "`make test` first. If it is intended, re-run with BENCH_ARGS=--allow-lower, "
                f"explain it in the pull request, and ask for the `{APPROVAL_LABEL}` label."
            )
            return 1
    text = dump_baseline(current)
    unchanged = args.baseline.is_file() and args.baseline.read_text(encoding="utf-8") == text
    args.baseline.parent.mkdir(parents=True, exist_ok=True)
    args.baseline.write_text(text, encoding="utf-8")
    shown = args.baseline.relative_to(ROOT) if args.baseline.is_relative_to(ROOT) else args.baseline
    verb = f"{shown} is already up to date with" if unchanged else f"wrote {shown} from"
    print(
        f"benchmark: {verb} {path.parent.name}: {len(current['passing_tests'])} "
        f"passing tests, {current['m3_calls']['executions_total']} M3 executions, "
        f"{len(current['tools'])} tools"
    )
    return 0


def run_agent(args: argparse.Namespace) -> int:
    try:
        base = json.loads(args.baseline.read_text(encoding="utf-8"))
        current = json.loads(args.agent.read_text(encoding="utf-8"))
        rows = compare_agent(base, current)
    except (OSError, json.JSONDecodeError, KeyError, TypeError) as exc:
        raise ValueError(f"cannot compare agent results: {exc!r}") from exc
    harness = current.get("harness", "?")
    print(f"Agent tool-selection pass rates ({harness}): {args.agent} vs the committed file\n")
    print(render_table(rows))
    summary = [
        f"### Agent pass rates ({harness}): at most one trial below the committed file\n",
        render_table(rows),
    ]
    down = regressions(rows)
    if down:
        text = (
            f"The {harness} agent lane picked the right tool less often than "
            f"`docs/results/agent-{harness}-latest.json` records, by more than one trial:\n\n"
            + "\n".join(f"- `{r.metric}`: {r.baseline} -> {r.now}" for r in down)
            + "\n\nThis run used "
            f"{current.get('trials', '?')} trial(s) per prompt against {base.get('trials', '?')} "
            f"in the committed file. Read the failing trials in the `m3-agent-reports-{harness}` "
            "artifact before changing anything: one model on one night can be wrong by chance, "
            "but a prompt that fails again points at the tool descriptions."
        )
        print("\nFAIL: agent pass rates dropped:")
        print(describe(down))
        summary.append("\n**FAIL: agent pass rates dropped.**")
        if args.markdown_out:
            args.markdown_out.write_text(text + "\n", encoding="utf-8")
    elif improvements(rows):
        print(
            "\nSome prompts improved. To keep the higher rates, copy the new file into "
            "docs/results/ and run `make adapters-md`."
        )
    write_summary("\n".join(summary))
    return 1 if down else 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Check or update the M3 benchmark (scores a pull request must not lower).",
        epilog="Exit codes: 0 ok, 1 a score went down, 2 input could not be read.",
    )
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="compare the latest report (default)")
    mode.add_argument(
        "--update", action="store_true", help="write the baseline from the latest report"
    )
    mode.add_argument("--agent", type=Path, metavar="CURRENT.json", help="compare agent pass rates")
    parser.add_argument("--baseline", type=Path, default=BASELINE_PATH, help="baseline file")
    parser.add_argument(
        "--pr-baseline", type=Path, help="the pull request's own baseline file (CI)"
    )
    parser.add_argument("--report", type=Path, help="feedback.json to read (default: newest)")
    parser.add_argument(
        "--reports-dir", type=Path, default=REPORTS_DIR, help="where M3 reports live"
    )
    parser.add_argument(
        "--allow-lower", action="store_true", help="let --update lower the baseline"
    )
    parser.add_argument("--markdown-out", type=Path, help="with --agent: write drops here")
    args = parser.parse_args(argv)
    try:
        if args.update:
            return run_update(args)
        if args.agent:
            return run_agent(args)
        return run_check(args)
    except ValueError as exc:
        print(f"benchmark: {exc}", file=sys.stderr)
        return 2


